import { readFileSync } from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const html = readFileSync("admin-marketplace.html", "utf8");
const admin = readFileSync("admin.html", "utf8");
assert.match(html, /<html[^>]*lang="ar"[^>]*dir="rtl"/, "Operations console must be Arabic RTL");
assert.match(html, /name="robots" content="noindex,nofollow"/, "Operations console must not be indexed");
assert.match(admin, /admin-marketplace\.html/, "Submission review page must link to marketplace operations");
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
assert.equal(new Set(ids).size, ids.length, "Operations console contains duplicate DOM IDs");
const inline = html.match(/<script>\s*([\s\S]*?)\s*<\/script>/i);
assert.ok(inline, "Operations console inline script is missing");
new vm.Script(inline[1], { filename: "admin-marketplace.html:inline-script" });
for (const endpoint of ["/api/v1/admin/marketplace/summary", "/api/v1/admin/marketplace/entities", "/api/v1/admin/marketplace/audit", "/api/v1/admin/marketplace/"]) assert.ok(inline[1].includes(endpoint), "Missing operations API endpoint: " + endpoint);
assert.match(inline[1], /Authorization:\s*"Bearer "\+key/, "Admin key must be sent as an authorization header");
assert.doesNotMatch(inline[1], /localStorage|sessionStorage|document\.cookie/, "Admin key must not be persisted in browser storage");
assert.match(inline[1], /checkout_enabled/, "Payment readiness must be displayed without enabling checkout");
assert.match(inline[1], /owner_verified/, "Store ownership verification must be shown separately");
assert.doesNotMatch(inline[1], /\/api\/v1\/map\//, "Operations console must not depend on map endpoints");
console.log("Admin marketplace operations validation passed:", JSON.stringify({ ids: ids.length, inlineScript: "passed", secretPersistence: "none" }));
